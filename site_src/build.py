"""
Build the site's generated pages from the repository's own sources.

THE ONE RULE. The review deck was hand-written, so it drifted until it
contradicted the repository in five places on the day two hardening items
closed. This site is the opposite: nothing here is a second copy of anything.
The manuscript is split from paper/manuscript.md, the figures are regenerated
from results/, and every number on the home page is read from a results/*.json
at build time. If a number is not in a tracked artifact it does not appear —
which is Rules.md §7 applied to a website.

    python3 site_src/build.py      # writes site_src/docs/** (generated parts)
    mkdocs build                   # renders site/
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import time

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(REPO, "site_src", "docs")
GEN_MARK = "<!-- generated by site_src/build.py — do not edit; edit the source it names -->\n"

DISCLAIMER = """!!! warning "Work in progress — this is not the submitted paper"
    This manuscript is a **living draft**, rendered from `paper/manuscript.md`
    at every push. It has not been peer-reviewed, the venue is undecided, and
    sections may change without notice. Every number in it traces to a committed
    artifact under `results/`, but the text is not final. Cite the repository,
    not this page.

"""


def _load(rel):
    with open(os.path.join(REPO, rel)) as fh:
        return json.load(fh)


# ── figures ──────────────────────────────────────────────────────────────
def figures():
    """Regenerate from results/ when the toolchain is present, then copy."""
    # Opt-in: matplotlib re-stamps the PDFs on every run and dirties the tree.
    # The committed figures ARE generated from results/ — make_figures.py is
    # the only thing that writes them — so copying them keeps the guarantee.
    if os.environ.get("SITE_REGEN_FIGURES"):
        subprocess.run(["python3", "paper/make_figures.py"], cwd=REPO,
                       check=True, capture_output=True, timeout=300)
        print("[site] figures regenerated from results/")
    dst = os.path.join(DOCS, "assets", "figures")
    os.makedirs(dst, exist_ok=True)
    for name in os.listdir(os.path.join(REPO, "paper", "figures")):
        if name.endswith((".png", ".pdf")):
            shutil.copy(os.path.join(REPO, "paper", "figures", name), dst)
    shutil.copy(os.path.join(REPO, "AdaptiShield_Architecture_v3.drawio.png"),
                os.path.join(dst, "implementation_architecture.png"))


# ── manuscript ───────────────────────────────────────────────────────────
def _slug(heading):
    s = re.sub(r"[^a-z0-9]+", "-", heading.lower()).strip("-")
    return s[:60]


def manuscript():
    """Split paper/manuscript.md into one page per section, in order."""
    src = open(os.path.join(REPO, "paper", "manuscript.md")).read()
    src = src.replace("](figures/", "](../assets/figures/")
    src = src.replace("](../AdaptiShield_Architecture_v3.drawio.png)",
                      "](../assets/figures/implementation_architecture.png)")

    parts = re.split(r"^(## .+)$", src, flags=re.M)
    front, sections = parts[0], list(zip(parts[1::2], parts[2::2]))
    out = os.path.join(DOCS, "manuscript")
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)

    nav = []
    # front matter page: title, authors, abstract
    with open(os.path.join(out, "index.md"), "w") as fh:
        fh.write(GEN_MARK + DISCLAIMER + front.strip() + "\n\n"
                 "---\n\n## Sections\n\n")
        for i, (h, _) in enumerate(sections, 1):
            title = h[3:].strip()
            fh.write(f"{i}. [{title}]({i:02d}-{_slug(title)}.md)\n")
        fh.write("\n[Download the Word draft](https://github.com/ahmadkhanraj01/"
                 "adaptishield/raw/main/paper/AdaptiShield-Manuscript.docx)\n")
    nav.append(("Front matter & abstract", "manuscript/index.md"))

    for i, (h, body) in enumerate(sections, 1):
        title = h[3:].strip()
        fname = f"{i:02d}-{_slug(title)}.md"
        with open(os.path.join(out, fname), "w") as fh:
            fh.write(GEN_MARK + DISCLAIMER + f"# {title}\n" + body)
        nav.append((title, f"manuscript/{fname}"))
    print(f"[site] manuscript: {len(sections)} sections")
    return nav


# ── numbers, from results/ only ──────────────────────────────────────────
def numbers():
    camp = _load("results/campaign/campaign.json")["summary"]
    nf = _load("results/noise_floor/agentdojo_benign.json")["summary"]
    tr = _load("results/phase16_model_transfer/transfer.json")
    inc, cand = tr["models"]["incumbent"], tr["models"]["candidate"]

    def pct(x): return f"{100*x:.1f}%"
    def ci(r): return f"[{100*r['ci_low']:.1f}%, {100*r['ci_high']:.1f}%]"

    det, ext = camp["detection"], camp["benign"]["fpr_external"]
    t_inc, t_cand = tr["per_model"][inc], tr["per_model"][cand]
    return {
        "detection": (f"{det['hits']}/{det['n']} = {pct(det['rate'])}", ci(det), "results/campaign/"),
        "fpr": (f"{ext['hits']}/{ext['n']} = {pct(ext['rate'])}", ci(ext) + f" · stable over {nf['n_runs']} recordings", "results/noise_floor/"),
        "strat_inc": (f"{pct(t_inc['IA-target']['rate'])} vs {pct(t_inc['IA-notarget']['rate'])}", f"{inc} · gap {100*tr['gap'][inc]:.1f} pts", "results/phase16_model_transfer/"),
        "strat_cand": (f"{pct(t_cand['IA-target']['rate'])} vs {pct(t_cand['IA-notarget']['rate'])}", f"{cand} · gap {100*tr['gap'][cand]:.1f} pts", "results/phase16_model_transfer/"),
        "misses": (", ".join(camp["misses"]), "every one address-free", "results/campaign/"),
    }


