def _git(*args):
    return subprocess.run(("git",) + args, cwd=REPO, capture_output=True,
                          text=True).stdout.strip()


GITHUB = "https://github.com/ahmadkhanraj01/adaptishield/blob/main/"


def _repo_links(md):
    """Relative links to repo files (README.md, Rules.md, evaluation/...) become
    GitHub links — those files are deliberately not part of the site."""
    return re.sub(r"\]\(((?!https?://|#|assets/|manuscript/)[^)]+\.(?:md|py|json|txt|yaml|yml|html))(#[^)]*)?\)",
                  lambda m: f"]({GITHUB}{m.group(1)}{m.group(2) or ''})", md)


